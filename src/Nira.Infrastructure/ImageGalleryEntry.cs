using System.Text.Json;
using Nira.Core;

namespace Nira.Infrastructure;

/// <summary>Gallery index reconstructed only from successful, bound, saved observations.</summary>
public sealed record ImageGalleryEntry(string Path, string Sha256, string Title, string Author,
    string License, string Source, DateTimeOffset RetrievedUtc, bool IsGenerated = false, bool IsAnimated = false, int FrameDurationMs = 0, bool IsLocalCapture = false)
{
    // Private desktop captures are visible in their originating chat only. The
    // global photo library continues to index public retrievals and generated art.
    public static IReadOnlyList<ImageGalleryEntry> ForChat(ConversationState state)
    {
        var captures = RecordedFileArtifacts.From(state).Where(file => file.ToolName == "desktop.window_capture")
            .Select(file => new ImageGalleryEntry(file.Path, file.Sha256,
                file.Title.Length == 0 ? "Window screenshot" : file.Title,
                "Local window capture", "Private · saved locally", "", state.UpdatedUtc, IsLocalCapture: true));
        return captures.Concat(FromTask(state)).ToArray();
    }

    public static IReadOnlyList<ImageGalleryEntry> FromTask(ConversationState state)
    {
        var candidates = ImageEvidenceBinding.Candidates(state).ToArray();
        var entries = new List<ImageGalleryEntry>();
        foreach (var op in state.Operations.Where(o => o.ToolName == "image.retrieve" &&
                     o.Status == OperationStatus.Succeeded && o.ResultJson is not null))
        {
            try
            {
                using var doc = JsonDocument.Parse(op.ResultJson!);
                var root = doc.RootElement;
                if (!root.GetProperty("Success").GetBoolean()) continue;
                foreach (var item in root.GetProperty("Data").GetProperty("previews").EnumerateArray())
                {
                    string url = ImageEvidenceBinding.Field(item, "url");
                    var candidate = candidates.FirstOrDefault(c => url.Length > 0 &&
                        (ImageEvidenceBinding.Field(c, "MediaUrl") == url || ImageEvidenceBinding.Field(c, "ThumbnailUrl") == url));
                    if (candidate.ValueKind != JsonValueKind.Object) continue;
                    string path = ImageEvidenceBinding.Field(item, "path"), hash = ImageEvidenceBinding.Field(item, "sha256");
                    if (path.Length == 0 || hash.Length != 64 || !hash.All(Uri.IsHexDigit)) continue;
                    entries.Add(new(path, hash, ImageEvidenceBinding.Field(candidate, "Title").Replace("File:", "", StringComparison.Ordinal),
                        ImageEvidenceBinding.Field(candidate, "Author"), ImageEvidenceBinding.Field(candidate, "License"),
                        ImageEvidenceBinding.Field(candidate, "SourceUrl"), op.CompletedUtc ?? op.CreatedUtc));
                }
            }
            catch (Exception ex) when (ex is JsonException or InvalidOperationException or KeyNotFoundException) { }
        }
        foreach (var op in state.Operations.Where(o => o.ToolName == "image.generate" &&
                     o.Status == OperationStatus.Succeeded && o.ResultJson is not null))
        {
            try
            {
                using var doc = JsonDocument.Parse(op.ResultJson!);
                var root = doc.RootElement;
                if (!root.GetProperty("Success").GetBoolean() || !root.GetProperty("ChangedState").GetBoolean()) continue;
                var item = root.GetProperty("Data");
                if (!item.GetProperty("generated").GetBoolean() || ImageEvidenceBinding.Field(item, "model") != ImageGenerationProvider.Model) continue;
                string path = ImageEvidenceBinding.Field(item, "path"), hash = ImageEvidenceBinding.Field(item, "sha256");
                if (path.Length == 0 || hash.Length != 64 || !hash.All(Uri.IsHexDigit)) continue;
                bool animated = item.TryGetProperty("animated", out var a) && a.ValueKind == JsonValueKind.True;
                int delay = 0;
                if (animated && (!item.TryGetProperty("frameCount", out var count) || !count.TryGetInt32(out int n) || n != 4 ||
                    !item.TryGetProperty("frameDurationMs", out var timing) || !timing.TryGetInt32(out delay) || delay is < 100 or > 2000 || delay % 10 != 0)) continue;
                entries.Add(new(path, hash, ImageEvidenceBinding.Field(item, "title"), "Generated by NIRA · FLUX.2 Klein 4B",
                    animated ? "AI-generated animation" : "AI-generated artwork", "", op.CompletedUtc ?? op.CreatedUtc, IsGenerated: true, IsAnimated: animated, FrameDurationMs: delay));
            }
            catch (Exception ex) when (ex is JsonException or InvalidOperationException or KeyNotFoundException) { }
        }
        return entries;
    }
}
